def unavailable_reason(graph: Graph) -> str:
    """Why `graph` cannot be built here, or an empty string."""
    missing = [m for m in graph.needs_modules if importlib.util.find_spec(m) is None]
    if missing:
        return f"needs {', '.join(missing)}"
    if graph.needs_ros:
        try:
            importlib.import_module("rclpy")
            # installed by the colcon build; the source folder aicon_ros/ alone would make aicon_ros.msg importable
            importlib.import_module("aicon_ros_python_wrapping")
            importlib.import_module("aicon_ros.msg")
        except ImportError:
            return "needs ROS 2 with the built aicon_ros messages"
    usable_gpus = torch.cuda.device_count() if torch.cuda.is_available() else 0
    if usable_gpus < graph.gpus:
        return f"needs {graph.gpus} usable CUDA device(s)"
    return ""


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only report files that differ, exit 1 if any does")
    args = parser.parse_args()

    if any(g.needs_ros and not unavailable_reason(g) for g in GRAPHS):
        # some real-robot components create ROS nodes even in mock mode; the context ends with the process
        importlib.import_module("rclpy").init()
    differing = []
    for graph in GRAPHS:
        reason = unavailable_reason(graph)
        if reason:
            print(f"skipped  {graph.spec_file} ({reason})")
            continue
        text = graph.text()
        path = os.path.join(REPOSITORY_ROOT, graph.spec_file)
        current = open(path).read() if os.path.exists(path) else None
        if current == text:
            print(f"current  {graph.spec_file}")
        elif args.check:
            differing.append(graph.spec_file)
            print(f"differs  {graph.spec_file}")
        else:
            with open(path, "w") as f:
                f.write(text)
            print(f"written  {graph.spec_file}")
    if differing:
        sys.exit(1)


if __name__ == "__main__":
    main()
