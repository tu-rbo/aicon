import logging
import sys
from pathlib import Path

from reader.spec.spec_types import SpecComponents, SpecConnectionProps

logger = logging.getLogger(__name__)


def gen_connections(
    location: Path,
    connection: dict[str, SpecConnectionProps],
    components: SpecComponents,
):
    connection_content = gen_connection_head()
    found_connection = False
    for connection_props in connection.values():
        print(f"Found connection: {connection_props.class_name}")
        found_connection = True
        connection_content += gen_connection(
            connection_props.class_name, connection_props, components
        )
    if found_connection:
        connection_content += gen_build_connections(connection)

    if found_connection:
        connection_path = Path(f"{location.resolve()}/connections.py")
        connection_path.write_text(connection_content)


def gen_connection_head():
    return """# Autogenerated
from typing import Union

import torch

from aicon_base.components.base_components import ActiveInterconnection
"""


def gen_connection(
    name: str, connection_props: SpecConnectionProps, components: SpecComponents
):
    # build quantites from connections
    quantities_and_shapes: dict[str, tuple[int, ...]] = {}
    for comp_name in connection_props.components:
        # find component in Components
        if comp_name not in components:
            logger.error(
                "Error: %s not defined but used in connection %s",
                comp_name,
                name,
            )
            sys.exit(2)

        comp = components[comp_name]
        for quantity, q_props in comp.quantities.items():
            quantities_and_shapes[quantity] = q_props.shape

    print(quantities_and_shapes)
    return f"""
class {name}(ActiveInterconnection):
    def __init__(
        self,
        name: str,
        dtype: Union[torch.dtype, None] = None,
        device: Union[torch.device, None] = None,
        mockbuild: bool = False,
    ):
        super().__init__(
            name,
            {quantities_and_shapes!s},
            dtype=dtype,
            device=device,
            mockbuild=mockbuild,
        )

    def define_implicit_connection_function(self):
        def connection_func():
            pass

        return connection_func
    """


def gen_build_connections(connections: dict[str, SpecConnectionProps]) -> str:
    content = """

def build_connections():
    connections = {
"""
    for connection_name, connection_props in connections.items():
        content += (
            f'        "{connection_name}": lambda device, dtype, mockbuild: '
            f'{connection_props.class_name}("{connection_name}", '
            "device=device, dtype=dtype, mockbuild=mockbuild),\n"
        )
    content += """    }
    return connections
"""
    return content
