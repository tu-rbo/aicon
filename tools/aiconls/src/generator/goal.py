from pathlib import Path

from reader.spec.spec_types import SpecGoals


def gen_goals(location: Path, goals: SpecGoals):
    if not goals:
        return

    goal_content = gen_goal_head()
    for goal_name, goal_props in goals.items():
        goal_content += gen_goal(goal_props.name or goal_name)

    goal_path = Path(f"{location.resolve()}/goals.py")
    goal_path.write_text(goal_content)


def gen_goal_head():
    return """# Autogenerated
from typing import Union

import torch

from aicon_base.components.goals import Goal
"""


def gen_goal(name: str):
    return f"""
class {name}(Goal):
    def __init__(
        self,
        is_active: bool = True,
        dtype: Union[torch.dtype, None] = None,
        device: Union[torch.device, None] = None,
        mockbuild: bool = False,
    ):
        super().__init__(
            name="{name}",
            is_active=is_active,
            dtype=dtype,
            device=device,
            mockbuild=mockbuild,
        )

    def define_goal_cost_function(self):
        def goal_func(*_args):
            cost = torch.zeros(1, dtype=self.dtype, device=self.device)
            return (cost,), (cost,)

        return goal_func
"""
