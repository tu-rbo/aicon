from pathlib import Path

from reader.spec.spec_types import (
    SpecComponents,
    SpecComponentTypes,
    SpecConnections,
    SpecGoals,
)


def _render_import(module_name: str, names: list[str]) -> str:
    if not names:
        return ""
    unique_names = sorted(set(names))
    return f"from {module_name} import {', '.join(unique_names)}\n"


def _resolve_goal_reference(
    goal_reference: str, goals: SpecGoals
) -> tuple[str, str] | None:
    if goal_reference in goals:
        return goal_reference, goals[goal_reference].name

    for goal_key, goal_props in goals.items():
        if goal_props.name == goal_reference:
            return goal_key, goal_props.name

    return None


def gen_experiment_specifications(
    location: Path,
    components: SpecComponents,
    goals: SpecGoals,
    connections: SpecConnections,
) -> None:
    sensor_components = [
        props.class_name
        for props in components.values()
        if props.component_type == SpecComponentTypes.Sensor
    ]
    estimator_components = [
        props.class_name
        for props in components.values()
        if props.component_type == SpecComponentTypes.Estimator
    ]
    action_components = [
        props.class_name
        for props in components.values()
        if props.component_type == SpecComponentTypes.Action
    ]
    goal_classes = [goal_props.name for goal_props in goals.values()]

    content = """# Autogenerated
from typing import Dict, Tuple

import torch
"""
    content += "from connections import build_connections\n"
    content += _render_import("goals", goal_classes)
    content += _render_import("sensors", sensor_components)
    content += _render_import("estimators", estimator_components)
    content += _render_import("actions", action_components)
    content += """

DTYPE = torch.double


def get_building_functions(sim_env_pointer=None) -> Tuple[Dict, Dict, Dict]:
"""
    content += "    connection_builders = build_connections()\n\n"

    content += "    component_builders = {\n"
    for component_name, component_props in components.items():
        if component_props.component_type == SpecComponentTypes.Goal:
            continue

        connected_keys = [
            key
            for key, connection_props in connections.items()
            if component_name in connection_props.components
        ]
        connection_tuple = ", ".join([f'"{key}"' for key in connected_keys])
        if connection_tuple and len(connected_keys) == 1:
            connection_tuple = f"{connection_tuple},"

        goal_entries: list[str] = []
        for goal_ref in component_props.goals:
            resolved = _resolve_goal_reference(goal_ref, goals)
            if resolved is None:
                continue
            goal_key, goal_class = resolved
            goal_entries.append(
                f'"{goal_key}": lambda device, dtype, mockbuild=False: {goal_class}(is_active=True, dtype=dtype, device=device, mockbuild=mockbuild)'
            )

        kwargs = [
            f'name="{component_name}"',
            f"connections={{k: connection_builders[k] for k in ({connection_tuple})}}",
            (
                f"dtype=torch.{component_props.dtype}"
                if component_props.dtype is not None
                else "dtype=DTYPE"
            ),
        ]
        if component_props.component_type == SpecComponentTypes.Sensor:
            kwargs.append("sim_env_pointer=sim_env_pointer")
        elif goal_entries:
            kwargs.append(f"goals={{{', '.join(goal_entries)}}}")

        content += (
            f'        "{component_name}": lambda mockbuild=False: {component_props.class_name}'
            f"({', '.join(kwargs)}),\n"
        )
    content += "    }\n\n"

    content += "    frame_rates = {\n"
    for component_name, component_props in components.items():
        if component_props.component_type == SpecComponentTypes.Goal:
            continue
        content += f'        "{component_name}": 10,\n'
    content += "    }\n\n"
    content += "    return component_builders, connection_builders, frame_rates\n"

    output_path = Path(f"{location.resolve()}/experiment_specifications.py")
    output_path.write_text(content)
