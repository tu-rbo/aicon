import logging
import sys
from pathlib import Path

from generator.quantities import gen_init_quantities
from reader.spec.spec_types import SpecComponentProps, SpecComponentTypes

logger = logging.getLogger(__name__)


def gen_sensors(location: Path, components: dict[str, SpecComponentProps]):
    sensor_content = gen_sensor_head()
    found_sensor = False
    for comp in components.values():
        if comp.component_type == SpecComponentTypes.Sensor:
            found_sensor = True
            sensor_content += gen_sensor(comp.class_name, comp)

    if found_sensor:
        sensor_path = Path(f"{location.resolve()}/sensors.py")
        sensor_path.write_text(sensor_content)


def gen_sensor_head():
    return """# Autogenerated

import torch

from typing import Any, Callable, Dict, Union

from aicon_base.components.sensor_components import SensorComponent

"""


def gen_sensor(name: str, sensor: SpecComponentProps):
    if sensor.component_type != SpecComponentTypes.Sensor:
        logger.error(
            "Error: could not generate estimator %s - wrong type %s",
            name,
            sensor.component_type,
        )
        sys.exit(1)

    init_quantites = ""
    quantity_names_and_shapes = "cls_quantity_names_and_shapes = {"
    for quant_name, quantity in sensor.quantities.items():
        init_quantites += gen_init_quantities(quant_name, quantity) + "\n"
        quantity_names_and_shapes += f'"{quant_name}" : {quantity.shape}, '
    quantity_names_and_shapes = quantity_names_and_shapes[:-2] + "}"

    return f"""
class {name}(SensorComponent):
    {quantity_names_and_shapes}

    def __init__(
        self,
        name: str,
        connections: Dict[str, Callable],
        dtype: Union[torch.dtype, None] = None,
        device: Union[torch.device, None] = None,
        mockbuild: bool = False,
        sim_env_pointer: Any = None,
    ):
        self.sim_env_pointer = sim_env_pointer
        super().__init__(
            name, connections, dtype=dtype, device=device, mockbuild=mockbuild
        )

    def obtain_measurements(self) -> bool:
        return True

    def initialize_quantities(self):
{init_quantites}
        return True
    """
