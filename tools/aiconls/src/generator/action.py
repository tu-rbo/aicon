import logging
import sys
from pathlib import Path

from generator.quantities import gen_init_quantities
from reader.spec.spec_types import SpecComponentProps, SpecComponentTypes

logger = logging.getLogger(__name__)


def gen_actions(location: Path, components: dict[str, SpecComponentProps]):
    action_content = gen_action_head()
    found_action = False
    for comp in components.values():
        if comp.component_type == SpecComponentTypes.Action:
            found_action = True
            action_content += gen_action(comp.class_name, comp)

    if found_action:
        action_path = Path(f"{location.resolve()}/actions.py")
        action_path.write_text(action_content)


def gen_action_head():
    return """# Autogenerated

import torch

from typing import Callable, Dict, Union

from aicon_base.components.action_components import ActionComponent

"""


def gen_action(name: str, action: SpecComponentProps):
    if action.component_type != SpecComponentTypes.Action:
        logger.error(
            "Error: could not generate action %s - wrong type %s",
            name,
            action.component_type,
        )
        sys.exit(1)

    init_quantites = ""
    quantity_names_and_shapes = "cls_quantity_names_and_shapes = {"
    for quant_name, quantity in action.quantities.items():
        init_quantites += gen_init_quantities(quant_name, quantity) + "\n"
        quantity_names_and_shapes += f'"{quant_name}" : {quantity.shape}, '
    quantity_names_and_shapes = quantity_names_and_shapes[:-2] + "}"

    return f"""
class {name}(ActionComponent):
    {quantity_names_and_shapes}

    def __init__(
        self,
        name: str,
        connections: Dict[str, Callable],
        goals: Union[None, Dict[str, Callable]] = None,
        dtype: torch.dtype = torch.get_default_dtype(),
        device: torch.device = torch.get_default_device(),
        mockbuild: bool = False,
        forward_mode: bool = False,
        debug_mode: bool = False,
    ):
        super().__init__(
            name=name,
            connections=connections,
            goals=goals,
            forward_mode=forward_mode,
            dtype=dtype,
            device=device,
            mockbuild=mockbuild,
            debug_mode=debug_mode,
        )

    def _start(self):
        pass

    def _stop(self):
        pass

    def determine_new_actions(self):
        pass

    def send_action_values(self):
        pass

    def initialize_quantities(self):
{init_quantites}
        return True

    """
